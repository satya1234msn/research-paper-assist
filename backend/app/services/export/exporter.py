import os
import uuid
from datetime import datetime
from typing import Dict, Any, List
from backend.app.core.config import settings

class ExportService:
    """Generates PDF, DOCX, and TXT exports for research summaries, comparisons, roadmaps, and notes."""

    @staticmethod
    def export_content(
        title: str,
        content_sections: List[Dict[str, Any]],
        format_type: str = "pdf"
    ) -> Dict[str, str]:
        """Generates the requested document format and saves to storage."""
        format_clean = format_type.lower()
        file_id = uuid.uuid4().hex[:10]
        safe_title = "".join(c for c in title if c.isalnum() or c in (" ", "-", "_")).strip()[:40]
        file_name = f"{safe_title}_{file_id}.{format_clean}"
        exports_dir = os.path.join(settings.STORAGE_DIR, "exports")
        os.makedirs(exports_dir, exist_ok=True)
        file_path = os.path.join(exports_dir, file_name)

        if format_clean == "txt":
            ExportService._generate_txt(title, content_sections, file_path)
        elif format_clean == "docx":
            ExportService._generate_docx(title, content_sections, file_path)
        elif format_clean == "pdf":
            ExportService._generate_pdf(title, content_sections, file_path)
        else:
            raise ValueError(f"Unsupported format: {format_type}")

        download_url = f"{settings.API_V1_STR}/exports/download/{file_name}"
        return {
            "file_name": file_name,
            "file_path": file_path,
            "download_url": download_url
        }

    @staticmethod
    def _generate_txt(title: str, sections: List[Dict[str, Any]], path: str):
        with open(path, "w", encoding="utf-8") as f:
            f.write("=" * 70 + "\n")
            f.write(f"RESEARCHASSIST AI — RESEARCH EXPORT\n")
            f.write(f"Title: {title}\n")
            f.write(f"Generated: {datetime.utcnow().strftime('%Y-%m-%d %H:%M:%S UTC')}\n")
            f.write("=" * 70 + "\n\n")

            for s in sections:
                heading = s.get("heading", "")
                body = s.get("body", "")
                f.write(f"## {heading.upper()}\n")
                f.write("-" * 40 + "\n")
                if isinstance(body, list):
                    for item in body:
                        f.write(f"  * {item}\n")
                else:
                    f.write(f"{body}\n")
                f.write("\n\n")

    @staticmethod
    def _generate_docx(title: str, sections: List[Dict[str, Any]], path: str):
        try:
            from docx import Document
            from docx.shared import Inches, Pt, RGBColor
            doc = Document()

            # Set title
            h1 = doc.add_heading(title, level=0)
            p = doc.add_paragraph()
            r = p.add_run(f"Generated by ResearchAssist AI on {datetime.utcnow().strftime('%B %d, %Y')}")
            r.font.italic = True
            r.font.size = Pt(10)
            r.font.color.rgb = RGBColor(100, 116, 139)

            for s in sections:
                heading = s.get("heading", "")
                body = s.get("body", "")
                doc.add_heading(heading, level=1)
                if isinstance(body, list):
                    for item in body:
                        doc.add_paragraph(str(item), style='List Bullet')
                else:
                    doc.add_paragraph(str(body))

            doc.save(path)
        except Exception as e:
            print(f"python-docx error ({e}), saving as fallback text.")
            ExportService._generate_txt(title, sections, path)

    @staticmethod
    def _generate_pdf(title: str, sections: List[Dict[str, Any]], path: str):
        try:
            from reportlab.lib.pagesizes import letter
            from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, HRFlowable
            from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
            from reportlab.lib import colors

            doc = SimpleDocTemplate(path, pagesize=letter, rightMargin=40, leftMargin=40, topMargin=40, bottomMargin=40)
            styles = getSampleStyleSheet()

            # Custom light academic styles
            title_style = ParagraphStyle(
                'DocTitle',
                parent=styles['Heading1'],
                fontSize=20,
                leading=24,
                textColor=colors.HexColor('#0F172A'),
                spaceAfter=6
            )
            meta_style = ParagraphStyle(
                'Meta',
                parent=styles['Normal'],
                fontSize=9,
                textColor=colors.HexColor('#64748B'),
                spaceAfter=14
            )
            heading_style = ParagraphStyle(
                'SectionHead',
                parent=styles['Heading2'],
                fontSize=13,
                leading=16,
                textColor=colors.HexColor('#1E293B'),
                spaceBefore=12,
                spaceAfter=6
            )
            body_style = ParagraphStyle(
                'Body',
                parent=styles['Normal'],
                fontSize=10,
                leading=14,
                textColor=colors.HexColor('#334155'),
                spaceAfter=6
            )

            story = [
                Paragraph(title, title_style),
                Paragraph(f"ResearchAssist AI Export &bull; {datetime.utcnow().strftime('%B %d, %Y')}", meta_style),
                HRFlowable(width="100%", thickness=1, color=colors.HexColor('#E2E8F0'), spaceAfter=14)
            ]

            for s in sections:
                heading = s.get("heading", "")
                body = s.get("body", "")
                story.append(Paragraph(heading, heading_style))
                if isinstance(body, list):
                    for item in body:
                        story.append(Paragraph(f"&bull; {item}", body_style))
                else:
                    # Clean line breaks
                    clean_body = str(body).replace("\n", "<br/>")
                    story.append(Paragraph(clean_body, body_style))
                story.append(Spacer(1, 8))

            doc.build(story)
        except Exception as e:
            print(f"ReportLab PDF error ({e}), saving fallback text.")
            ExportService._generate_txt(title, sections, path)

export_service = ExportService()
